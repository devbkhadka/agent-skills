"""Shared rendering harness for round 2's human-readable documents.

Owner: render-harness bead. Imported by `bin/render-glossary`, `bin/render-flow-simulation`,
`bin/render-entity-map` and `bin/render-slice-plan` so template loading, the do-not-edit banner
and the output file mode are defined once instead of four times with four small variations.

Rule R1 (improvement plan §2) says a rendered document is produced from a template plus an
artifact and never hand-edited; this module is where that becomes a build property instead of a
convention four renderers each remember on their own. Rule R2 lands here too: a template
placeholder with no value in `context` refuses rather than rendering blank, because a silently
empty section is the renderer deciding the section does not matter, and a `context` key the
template never uses refuses as well, because data the document does not show is data the next
reader assumes it covers.

Byte-identical re-rendering is required by the same rule that pins approval to a content digest
(R3): a document that changes when nothing changed makes that digest meaningless. Nothing in this
module reads a clock, randomness or the host, and nothing here should start.
"""

import string
from pathlib import Path
from typing import Any, Dict, Optional

DEFAULT_TEMPLATE_DIR = Path(__file__).resolve().parent.parent / "templates" / "docs"

_BANNER = (
    "<!-- DO NOT EDIT. Generated by {renderer_name} from {artifact_path}. -->\n"
    "<!-- Regenerate this document instead of hand-editing it; edits are overwritten. -->\n"
)


class RenderError(Exception):
    """Raised when a template and its context do not match each other exactly."""


def _declared_placeholders(template_text: str):
    pattern = string.Template.pattern
    names = set()
    for match in pattern.finditer(template_text):
        name = match.group("named") or match.group("braced")
        if name:
            names.add(name)
    return names


def render_document(
    template_name: str,
    context: Dict[str, Any],
    out_dir: Any,
    doc_name: str,
    artifact_path: str,
    renderer_name: str,
    template_dir: Optional[Any] = None,
) -> Path:
    """Render `template_name` with `context`, write it read-only, and return its path.

    Raises RenderError if a template placeholder has no value in `context`, or if `context`
    carries a key the template never uses. Both directions are closed: a document must show
    exactly the data it was given, no more and no less.
    """
    tdir = Path(template_dir) if template_dir is not None else DEFAULT_TEMPLATE_DIR
    template_path = tdir / template_name
    if not template_path.is_file():
        raise RenderError("template %r not found in %s" % (template_name, tdir))

    template_text = template_path.read_text(encoding="utf-8")
    placeholders = _declared_placeholders(template_text)
    context_keys = set(context.keys())

    missing = placeholders - context_keys
    if missing:
        raise RenderError(
            "template %r has placeholder(s) with no value in context: %s"
            % (template_name, ", ".join(sorted(missing)))
        )
    unused = context_keys - placeholders
    if unused:
        raise RenderError(
            "context key(s) %s are not used by template %r; a document must show exactly the "
            "data it was given" % (", ".join(sorted(unused)), template_name)
        )

    body = string.Template(template_text).substitute(context)
    banner = _BANNER.format(renderer_name=renderer_name, artifact_path=artifact_path)
    rendered = banner + body

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / doc_name

    if out_path.exists():
        out_path.chmod(0o644)
    out_path.write_text(rendered, encoding="utf-8")
    out_path.chmod(0o444)

    return out_path
